// File generators for 1-click downloads (NOTICE / GSTR-2B / GSTR-3B / GSTR-1)
const fs = require("fs");
const path = require("path");
const { DATA_DIR } = require("./store");

function inr(n) {
  return "₹" + Number(n || 0).toLocaleString("en-IN", { minimumFractionDigits: 2 });
}

// ---------- Minimal, valid single/multi-line PDF (Helvetica) ----------
function buildPdf(title, lines) {
  const esc = (s) =>
    String(s)
      .replace(/\\/g, "\\\\")
      .replace(/\(/g, "\\(")
      .replace(/\)/g, "\\)");

  let content = "BT /F1 15 Tf 50 790 Td (" + esc(title) + ") Tj ET\n";
  let y = 760;
  for (const ln of lines) {
    if (y < 60) break;
    const text = ln === "" ? "" : esc(ln);
    const bold = ln.startsWith("##");
    content += `BT ${bold ? "/F2 11" : "/F1 10"} Tf 50 ${y} Td (${bold ? esc(ln.slice(2)) : text}) Tj ET\n`;
    y -= bold ? 20 : 16;
  }

  const objects = [
    "<< /Type /Catalog /Pages 2 0 R >>",
    "<< /Type /Pages /Kids [3 0 R] /Count 1 >>",
    "<< /Type /Page /Parent 2 0 R /MediaBox [0 0 595 842] /Contents 4 0 R /Resources << /Font << /F1 5 0 R /F2 6 0 R >> >> >>",
    `<< /Length ${Buffer.byteLength(content, "utf8")} >>\nstream\n${content}endstream`,
    "<< /Type /Font /Subtype /Type1 /BaseFont /Helvetica >>",
    "<< /Type /Font /Subtype /Type1 /BaseFont /Helvetica-Bold >>",
  ];

  let pdf = "%PDF-1.4\n";
  const offsets = [];
  objects.forEach((obj, i) => {
    offsets.push(Buffer.byteLength(pdf, "utf8"));
    pdf += `${i + 1} 0 obj\n${obj}\nendobj\n`;
  });
  const xrefPos = Buffer.byteLength(pdf, "utf8");
  pdf += `xref\n0 ${objects.length + 1}\n0000000000 65535 f \n`;
  offsets.forEach((o) => {
    pdf += String(o).padStart(10, "0") + " 00000 n \n";
  });
  pdf += `trailer\n<< /Size ${objects.length + 1} /Root 1 0 R >>\nstartxref\n${xrefPos}\n%%EOF`;
  return Buffer.from(pdf, "utf8");
}

function safeName(s) {
  return String(s || "file").replace(/[^\w.\-]+/g, "_").slice(0, 80);
}

function writeDownload(fileName, buffer) {
  const dir = path.join(DATA_DIR, "downloads");
  if (!fs.existsSync(dir)) fs.mkdirSync(dir, { recursive: true });
  const full = path.join(dir, safeName(fileName));
  fs.writeFileSync(full, buffer);
  return { downloadUrl: "/downloads/" + encodeURIComponent(safeName(fileName)), fileName: safeName(fileName) };
}

// ---------- Content builders ----------
function noticePdf(clientName, gstin, notice, fp) {
  return writeDownload(
    `${gstin}_NOTICE_${notice.refId}.pdf`,
    buildPdf("GST PORTAL — OFFICIAL COPY (Notices & Demands)", [
      "##NOTICE DETAILS",
      `Client Name : ${clientName}`,
      `GSTIN       : ${gstin}`,
      `Financial P : ${fp || "-"}`,
      "",
      "##Notice Summary",
      `Ref ID      : ${notice.refId}`,
      `Type        : ${notice.type}`,
      `Description : ${notice.description}`,
      `Issue Date  : ${notice.issueDate}`,
      `Due Date    : ${notice.dueDate}`,
      `Status      : ${notice.status || "Pending Action"}`,
      "",
      "##Action Required",
      "- Reply to notice before due date from GST Portal (Services > User Services > Reply to Notices).",
      "- Attach relevant documents (invoices, ledgers, payment proofs) as annexures.",
      "",
      `Generated by KDK Engine — ${new Date().toUTCString()}`,
      "This is a system-generated copy for record keeping. The official record",
      "remains on the GST Portal (www.gst.gov.in).",
    ])
  );
}

function gstr2bJson(clientName, gstin, records, fp) {
  const payload = {
    header: { gstin, fp: fp || "", returnType: "GSTR-2B", generatedBy: "KDK Engine", generatedAt: new Date().toISOString() },
    client: clientName,
    inputTaxCredit: {
      tdsTcs: (records || []).map((r) => ({
        type: r.type, ctin: r.ctin, cname: r.cname, net: r.net,
        iamt: r.iamt, camt: r.camt, samt: r.samt, totalCredit: r.totalCredit, status: r.status,
      })),
      summary: {
        totalTdsTcsCredit: (records || []).reduce((s, r) => s + Number(r.totalCredit || 0), 0),
        totalNet: (records || []).reduce((s, r) => s + Number(r.net || 0), 0),
      },
    },
    note: "Simulated GSTR-2B TDS/TCS extract (KDK Engine demo mode).",
  };
  return writeDownload(`${gstin}_GSTR2B_${fp || ""}.json`, Buffer.from(JSON.stringify(payload, null, 2), "utf8"));
}

function gstr3bPdf(clientName, gstin, cd, fp) {
  return writeDownload(
    `${gstin}_GSTR3B_${fp || ""}.pdf`,
    buildPdf("GST Portal — GSTR-3B Return Summary (System Copy)", [
      `Client Name : ${clientName}`,
      `GSTIN       : ${gstin}`,
      `Period      : ${fp || "-"}`,
      "",
      "##Liability Summary (Simulated)",
      `   B2B Taxable Value   : ${inr(cd.taxableValue || 0)}`,
      `   IGST Liability      : ${inr((cd.taxableValue || 0) * 0.09)}`,
      `   CGST Liability      : ${inr((cd.taxableValue || 0) * 0.09)}`,
      `   SGST Liability      : ${inr((cd.taxableValue || 0) * 0.09)}`,
      "",
      "##ITC Available",
      `   Cash Ledger Balance : ${inr(cd.cashLedgerBalance || 0)}`,
      `   Credit Ledger Bal.  : ${inr(cd.creditLedgerBalance || 0)}`,
      `   TDS/TCS Credit      : ${inr((cd.tdsTcsRecords || []).reduce((s, r) => s + Number(r.totalCredit || 0), 0))}`,
      "",
      "##Net Tax Payable",
      "  (Liability - ITC) — as per portal; see GSTR-3B return for final figures.",
      "",
      `Generated by KDK Engine — ${new Date().toUTCString()}`,
    ])
  );
}

